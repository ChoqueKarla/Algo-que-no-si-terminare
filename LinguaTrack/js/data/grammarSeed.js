export function buildSeedGrammar() {
  const out = {};
  Object.entries(GRAMMAR_RAW).forEach(([lang, topics]) => {
    out[lang] = topics.map((t, i) => ({ ...t, id: `gram_${lang}_${i}` }));
  });
  return out;
}
